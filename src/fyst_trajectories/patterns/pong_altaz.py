"""AltAz-native Pong (curvy box) scan pattern.

Executes the Curvy-Pong pattern about a fixed horizon-frame center
(``az_center``, ``el_center``) with no sky tracking. The on-sky
tangent-plane offsets are generated by the celestial
:class:`~fyst_trajectories.patterns.PongScanPattern` (reused, not
re-derived) and mapped into telescope coordinates by a static horizon-frame
projection. See Scott & van Engelen 2005, "SCAN Mode Strategies for
SCUBA-2", SCUBA-2 Project document SC2/ANA/S210/005, section 4.3, for the
underlying algorithm.
"""

from astropy.time import Time

from ..site import AtmosphericConditions, Site
from ..trajectory import Trajectory, TrajectoryMetadata
from .base import AltAzPattern
from .configs import PongAltAzScanConfig
from .pong import PongScanPattern, compute_pong_period
from .registry import register_pattern
from .utils import _SCIENCE_SPEED_FRACTION, _altaz_offsets_to_trajectory, _flag_by_offset_speed


@register_pattern("pong_altaz", config=PongAltAzScanConfig)
class PongAltAzScanPattern(AltAzPattern):
    """Curvy-Pong scan about a fixed AltAz center.

    Generates the same Fourier-truncated Pong offsets as
    :class:`~fyst_trajectories.patterns.PongScanPattern`, then maps
    them into telescope coordinates about a fixed horizon-frame center::

        az = x_offset / cos(radians(el_center)) + az_center
        el = y_offset + el_center

    The pattern does not track the sky: ``el_center`` is constant, so the
    ``cos(el_center)`` azimuth stretch is a single scalar applied to every
    sample. As an :class:`AltAzPattern` it needs no coordinate transform or
    ``start_time`` to build.

    The offset generation is delegated to a celestial
    :class:`~fyst_trajectories.patterns.PongScanPattern` instance
    (constructed internally at ``ra=0``, ``dec=0``) so the Fourier
    triangle-wave math lives in exactly one place.

    Parameters
    ----------
    config : PongAltAzScanConfig
        Scan configuration parameters.

    Attributes
    ----------
    config : PongAltAzScanConfig
        The configuration for this pattern.

    Examples
    --------
    >>> from fyst_trajectories.patterns import PongAltAzScanConfig, PongAltAzScanPattern
    >>> config = PongAltAzScanConfig(
    ...     az_center=120.0,
    ...     el_center=60.0,
    ...     width=2.0,
    ...     height=2.0,
    ...     spacing=0.1,
    ...     velocity=0.4,
    ... )
    >>> pattern = PongAltAzScanPattern(config)
    >>> trajectory = pattern.generate(site, duration=60.0)
    """

    def __init__(self, config: PongAltAzScanConfig):
        self.config = config

    def _offset_pattern(self) -> PongScanPattern:
        """Build the celestial Pong that owns the on-sky offset generation.

        Returns
        -------
        PongScanPattern
            A celestial Pong whose ``generate_offsets`` produces the
            tangent-plane offsets this pattern maps into AltAz. Built
            at ``ra=dec=0`` from this pattern's own configuration, whose
            on-sky fields the celestial Pong reads directly: only the
            tangent-plane offsets are used.
        """
        return PongScanPattern(ra=0.0, dec=0.0, config=self.config)

    def generate(
        self,
        site: Site,
        duration: float,
        start_time: Time | None = None,
        atmosphere: AtmosphericConditions | None = None,
    ) -> Trajectory:
        """Generate the AltAz Pong scan trajectory.

        Parameters
        ----------
        site : Site
            Telescope site configuration.
        duration : float
            Total duration of the scan in seconds.
        start_time : Time or None, optional
            Start time for the trajectory. Optional; defaults to ``None``
            (acceptable for AltAz patterns where absolute time is not
            needed to build the geometry). When provided, it is attached
            to the trajectory so downstream output carries a UTC timestamp.
        atmosphere : AtmosphericConditions or None, optional
            Not used by this AltAz pattern (no coordinate transforms).
            Accepted for interface compatibility.

        Returns
        -------
        Trajectory
            The generated trajectory.

        Raises
        ------
        TrajectoryBoundsError
            If the trajectory exceeds telescope limits.
        ValueError
            If ``duration`` yields fewer than two samples at the config
            timestep.
        """
        offset_pattern = self._offset_pattern()
        times, x_offsets, y_offsets = offset_pattern.generate_offsets(duration)
        scan_flag = _flag_by_offset_speed(
            times, x_offsets, y_offsets, self.config.velocity, _SCIENCE_SPEED_FRACTION
        )
        return _altaz_offsets_to_trajectory(
            site,
            self.config.az_center,
            self.config.el_center,
            times,
            x_offsets,
            y_offsets,
            scan_flag,
            start_time,
            self.get_metadata(),
        )

    def get_metadata(self) -> TrajectoryMetadata:
        """Get pattern metadata.

        Returns
        -------
        TrajectoryMetadata
            Metadata including pattern type and parameters (period and
            vertex counts from
            :func:`~fyst_trajectories.patterns.compute_pong_period`, which
            reads the on-sky fields this configuration shares with the
            celestial Pong).
        """
        period, x_numvert, y_numvert = compute_pong_period(self.config)

        return TrajectoryMetadata(
            pattern_type=self.name,
            pattern_params={
                "az_center": self.config.az_center,
                "el_center": self.config.el_center,
                "width": self.config.width,
                "height": self.config.height,
                "spacing": self.config.spacing,
                "velocity": self.config.velocity,
                "num_terms": self.config.num_terms,
                "angle": self.config.angle,
                "period": period,
                "x_numvert": x_numvert,
                "y_numvert": y_numvert,
            },
        )
